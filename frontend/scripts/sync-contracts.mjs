import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(scriptDir, "..");
const exportsRoot = resolve(frontendRoot, "../contracts/exports");
const outputDir = resolve(frontendRoot, "src/lib/chain/generated");
const biomeBin = resolve(frontendRoot, "node_modules/.bin/biome");

const CONTRACTS = [
  { module: "workflowRegistry", artifact: "WorkflowRegistry" },
  { module: "strategyVault", artifact: "StrategyVault" },
  { module: "executor", artifact: "Executor" },
  { module: "vaultFactory", artifact: "VaultFactory" },
  { module: "demoToken", artifact: "DemoToken" },
  { module: "automationTrigger", artifact: "AutomationTrigger" },
];

const BANNER =
  "// Generated by scripts/sync-contracts.mjs from contracts/exports. Do not edit by hand.\n\n";

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function writeGenerated(fileName, body) {
  writeFileSync(resolve(outputDir, fileName), `${BANNER}${body}`, "utf8");
}

function toAbiModule({ module, artifact }) {
  const artifactPath = resolve(exportsRoot, "abi", `${artifact}.json`);
  const parsed = readJson(artifactPath);
  const abi = Array.isArray(parsed) ? parsed : parsed.abi;

  if (!Array.isArray(abi)) {
    throw new Error(`${artifact}.json does not contain an abi array`);
  }

  writeGenerated(
    `${module}.ts`,
    `export const ${module}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
}

function toDeploymentsModule() {
  const addresses = readJson(
    resolve(exportsRoot, "addresses.arc-testnet.json"),
  );

  writeGenerated(
    "deployments.ts",
    `export const ARC_TESTNET_DEPLOYMENT = ${JSON.stringify(addresses, null, 2)} as const;\n`,
  );
}

function toIndexModule() {
  const exportLines = CONTRACTS.map(
    ({ module }) => `export { ${module}Abi } from "./${module}";`,
  ).join("\n");

  writeGenerated(
    "index.ts",
    `${exportLines}\nexport { ARC_TESTNET_DEPLOYMENT } from "./deployments";\n`,
  );
}

mkdirSync(outputDir, { recursive: true });
CONTRACTS.forEach(toAbiModule);
toDeploymentsModule();
toIndexModule();
execFileSync(biomeBin, ["check", "--write", outputDir], { stdio: "inherit" });
